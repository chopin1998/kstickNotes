#!/bin/sh
set -eu
project_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
config_home=${XDG_CONFIG_HOME:-"$HOME/.config"}
data_home=${XDG_DATA_HOME:-"$HOME/.local/share"}
launcher_dir="$HOME/.local/bin"
mkdir -p "$launcher_dir" "$data_home/applications" "$data_home/icons/hicolor/scalable/apps"
# The wrapper uses the locked project environment and works from any directory.
python3 - "$project_dir" "$launcher_dir/kstickynotes" <<'PY'
import pathlib, shlex, sys
project, target = sys.argv[1:]
python = pathlib.Path(project) / '.venv/bin/python'
if not python.exists():
    raise SystemExit('请先在项目目录执行 uv sync --frozen')
path = pathlib.Path(target)
if path.exists() and 'Generated by KStickyNotes' not in path.read_text():
    raise SystemExit(f'拒绝覆盖已有文件：{path}')
path.write_text('#!/bin/sh\n# Generated by KStickyNotes\nexec ' + shlex.quote(str(python)) + ' -m kstickynotes "$@"\n')
path.chmod(0o755)
PY
python3 - "$project_dir" "$launcher_dir" "$data_home" <<'PY'
import pathlib, sys
project, launchers, data = map(pathlib.Path, sys.argv[1:])
source = (project / 'share/org.kstickynotes.KStickyNotes.desktop').read_text()
# Desktop Entry quoting is different from shell quoting.
executable = str(launchers / 'kstickynotes')
for char in ('\\', '"', '`', '$'):
    executable = executable.replace(char, '\\' + char)
executable = executable.replace('%', '%%')
source = source.replace('Exec=kstickynotes', f'Exec="{executable}"')
(data / 'applications/org.kstickynotes.KStickyNotes.desktop').write_text(source)
(data / 'icons/hicolor/scalable/apps/kstickynotes.svg').write_bytes((project / 'share/kstickynotes.svg').read_bytes())
PY
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$data_home/applications"
fi
printf '%s\n' '已安装用户级启动器。可以在 KDE 应用菜单中打开 KStickyNotes。'
